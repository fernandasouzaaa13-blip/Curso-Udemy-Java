package Do_While;

public class Exercicio1 {
    public static void main(String[] args) {
        System.out.print("==============================\n");
        System.out.print(" Todos os números de 1 até 100\n");
        System.out.print("==============================\n");

        int contador = 1;

        do {
            System.out.println(contador);
            contador++;

        } while (contador <= 100);

    }

}
